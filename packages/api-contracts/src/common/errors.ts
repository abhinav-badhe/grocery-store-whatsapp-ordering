import { z } from 'zod';

/**
 * Validation Error Item Schema for parameter-level validation details.
 */
export const InvalidParamSchema = z.object({
  name: z.string().min(1, { message: 'Parameter name cannot be empty' }),
  reason: z.string().min(1, { message: 'Failure reason cannot be empty' }),
});

export type InvalidParam = z.infer<typeof InvalidParamSchema>;

/**
 * RFC 7807 / RFC 9457 Problem Details Schema.
 * Standardized across all public and internal API error responses.
 *
 * SPECIFICATION & CONTRACT DISTINCTION:
 * Standard RFC 7807 / RFC 9457 members:
 * - type: URI reference identifying the problem type (RFC default: 'about:blank')
 * - status: HTTP status code generated by origin server (400-599)
 * - title: Human-readable summary of problem type
 * - detail: Human-readable explanation specific to this occurrence
 * - instance: URI reference identifying specific occurrence
 *
 * Platform Requirements (stricter than RFC):
 * - While the RFC allows title and detail to be omitted, our platform contract
 *   mandates `status`, `title`, and `detail` on every error response for consistent client parsing.
 *
 * Platform Extension Policy & Strictness:
 * - RFC 7807 §4 and RFC 9457 §3.2 explicitly allow arbitrary extension members.
 * - However, as a deliberate PLATFORM CONTRACT SECURITY POLICY (not an RFC requirement),
 *   ProblemDetailsSchema enforces `.strict()`. This ensures that public and inter-service
 *   error responses reject unvetted fields and cannot accidentally leak stack traces,
 *   raw database queries, SQL fragments, secrets, or internal network topology.
 * - Approved platform extensions are strictly limited to:
 *   - `code`: Platform-specific machine-readable error code (e.g. 'ORDER_NOT_FOUND')
 *   - `request_id`: Edge/gateway trace correlation UUID for support triage
 *   - `invalid_params`: Array of parameter-level validation failure details
 *
 * CONTRACT IMPLEMENTATION BOUNDARY:
 * This package defines the shared contract schema and creation helper only. The runtime error
 * mapping pipeline, gateway exception interceptors, and framework response builders that construct
 * these Problem Details objects will be implemented within the respective application services.
 */

export const ProblemDetailsSchema = z
  .object({
    type: z.string().min(1).default('about:blank'),
    title: z.string().min(1, { message: 'Title is required' }),
    status: z
      .number({ invalid_type_error: 'Status must be a number' })
      .int({ message: 'Status must be an integer HTTP status code' })
      .min(400, { message: 'Problem Details status must be an HTTP error code (>= 400)' })
      .max(599, { message: 'Problem Details status must be a valid HTTP error code (<= 599)' }),
    detail: z.string().min(1, { message: 'Detail is required' }),
    instance: z.string().optional(),
    // Explicit platform extensions
    code: z.string().min(1).optional(),
    request_id: z.string().uuid({ message: 'Request ID must be a valid UUID' }).optional(),
    invalid_params: z.array(InvalidParamSchema).optional(),
  })
  .strict();

export type ProblemDetails = z.infer<typeof ProblemDetailsSchema>;

/**
 * Helper to construct a validated Problem Details response.
 */
export function createProblemDetails(params: {
  status: number;
  title: string;
  detail: string;
  type?: string;
  instance?: string;
  code?: string;
  request_id?: string;
  invalid_params?: InvalidParam[];
}): ProblemDetails {
  return ProblemDetailsSchema.parse({
    type: params.type ?? 'about:blank',
    title: params.title,
    status: params.status,
    detail: params.detail,
    instance: params.instance,
    code: params.code,
    request_id: params.request_id,
    invalid_params: params.invalid_params,
  });
}
